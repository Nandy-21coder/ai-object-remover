class TestInpaintingServiceConfig:
    """Tests for InpaintingService provider resolution and status reporting."""

    def test_get_status_returns_dict_with_required_keys(self):
        """
        TC-INP-019
        Input:  Default InpaintingService instantiation.
        Expected: get_status() returns a dict with 'status', 'provider', and
                  'provider_configured' keys.
        """
        service = InpaintingService()
        result = service.get_status()
        assert isinstance(result, dict)
        for key in ("status", "provider", "provider_configured"):
            assert key in result, f"Missing key '{key}' in status dict: {result}"

    def test_lama_provider_is_configured_without_api_key(self):
        """
        TC-INP-020
        Input:  AI_PROVIDER environment variable set to 'lama'.
        Expected: get_provider_config() returns provider_name='lama' and
                  api_key='local' without raising ProviderNotConfiguredError.
        """
        os.environ["AI_PROVIDER"] = "lama"
        service = InpaintingService()
        provider_name, api_key, _ = service.get_provider_config()
        assert provider_name == "lama"
        assert api_key == "local"

    def test_adaptive_mask_params_scale_with_resolution(self):
        """
        TC-INP-021
        Input:  Image sizes: 512×512 and 2048×2048.
        Expected: Adaptive expansion and feather values are larger for the 2048
                  image than for the 512 image, demonstrating resolution-aware scaling.
        """
        exp_small, feat_small = MaskService.calculate_adaptive_mask_params(
            (512, 512), base_expansion=4, base_feather=2.0
        )
        exp_large, feat_large = MaskService.calculate_adaptive_mask_params(
            (2048, 2048), base_expansion=4, base_feather=2.0
        )
        assert exp_large > exp_small, (
            "Adaptive expansion should increase with image resolution"
        )
        assert feat_large > feat_small, (
            "Adaptive feather radius should increase with image resolution"
        )


