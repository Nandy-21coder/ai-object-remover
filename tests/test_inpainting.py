class TestMaskServiceLoadImage:
    """Unit tests for MaskService.load_image."""

    def test_valid_png_loads_successfully(self):
        """
        TC-INP-001
        Input:  Valid 64×64 PNG bytes.
        Expected: Returns a PIL Image in RGB or RGBA mode with correct dimensions.
        """
        img = MaskService.load_image(_png_bytes(64, 64))
        assert img is not None
        assert img.size == (64, 64)
        assert img.mode in ("RGB", "RGBA")

    def test_empty_bytes_raises_validation_error(self):
        """
        TC-INP-002
        Input:  Empty bytes (b'').
        Expected: MaskValidationError is raised with 'empty' in the message.
        """
        with pytest.raises(MaskValidationError, match="(?i)empty"):
            MaskService.load_image(b"")

    def test_corrupted_bytes_raises_validation_error(self):
        """
        TC-INP-003
        Input:  Bytes that are not a valid image format.
        Expected: MaskValidationError is raised.
        """
        with pytest.raises(MaskValidationError):
            MaskService.load_image(b"\x00\x01\x02\x03garbage")

    def test_valid_jpeg_loads_successfully(self):
        """
        TC-INP-004
        Input:  Valid JPEG bytes generated by Pillow.
        Expected: Returns a PIL Image with correct dimensions.
        """
        img_pil = Image.new("RGB", (32, 32), (200, 100, 50))
        buf = io.BytesIO()
        img_pil.save(buf, format="JPEG")
        result = MaskService.load_image(buf.getvalue())
        assert result.size == (32, 32)

    def test_unsupported_gif_format_raises_validation_error(self):
        """
        TC-INP-005
        Input:  Minimal valid GIF87a bytes.
        Expected: MaskValidationError is raised with 'Unsupported' in the message.
        Note: GIF is not in MaskService.SUPPORTED_FORMATS.
        """
        gif_bytes = (
            b"GIF87a\x01\x00\x01\x00\x80\x00\x00\xff\xff\xff"
            b"\x00\x00\x00!\xf9\x04\x00\x00\x00\x00\x00,"
            b"\x00\x00\x00\x00\x01\x00\x01\x00\x00\x02\x02D\x01\x00;"
        )
        with pytest.raises(MaskValidationError, match="(?i)unsupported"):
            MaskService.load_image(gif_bytes)


