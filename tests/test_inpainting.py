# TC-INP-006 — TC-INP-011: MaskService.load_and_binarize_mask
# ===========================================================================

class TestMaskServiceBinarize:
    """Unit tests for MaskService.load_and_binarize_mask."""

    def test_valid_grayscale_mask_binarizes_correctly(self):
        """
        TC-INP-006
        Input:  Grayscale PNG mask with central 30% coverage, target size 64×64.
        Expected: Returns L-mode PIL Image of size (64, 64) with pixels that are
                  strictly 0 or 255.
        """
        mask_bytes = _grayscale_mask_bytes(64, 64, 0.3)
        result = MaskService.load_and_binarize_mask(mask_bytes, (64, 64))
        assert result.mode == "L"
        assert result.size == (64, 64)
        # Verify strict binarization: every pixel is exactly 0 or 255
        arr = np.array(result)
        unique = set(arr.flatten().tolist())
        assert unique.issubset({0, 255}), f"Non-binary values found in mask: {unique - {0, 255}}"

    def test_empty_mask_raises_validation_error(self):
        """
        TC-INP-007
        Input:  Fully black (all-zero) PNG mask.
        Expected: MaskValidationError with 'empty' in the message.
        """
        mask_bytes = _empty_mask_bytes(64, 64)
        with pytest.raises(MaskValidationError, match="(?i)empty"):
            MaskService.load_and_binarize_mask(mask_bytes, (64, 64))

    def test_mask_resized_to_target_dimensions(self):
        """
        TC-INP-008
        Input:  32×32 mask with 30% coverage, target size (64, 64).
        Expected: Returned mask has size (64, 64) — mask is upscaled to match image.
        """
        mask_bytes = _grayscale_mask_bytes(32, 32, 0.3)
        result = MaskService.load_and_binarize_mask(mask_bytes, (64, 64))
        assert result.size == (64, 64), (
            f"Expected (64, 64), got {result.size}"
        )

    def test_rgba_mask_correctly_binarized(self):
        """
        TC-INP-009
        Input:  RGBA PNG mask where the foreground is set via alpha channel.
        Expected: Returns an L-mode mask with at least some white (255) pixels.
        """
        # Build RGBA image: central region is white fully opaque, rest transparent
        arr = np.zeros((64, 64, 4), dtype=np.uint8)
        arr[20:44, 20:44] = [255, 255, 255, 255]  # Foreground
        img = Image.fromarray(arr, mode="RGBA")
        buf = io.BytesIO()
        img.save(buf, format="PNG")
        result = MaskService.load_and_binarize_mask(buf.getvalue(), (64, 64))
        mask_arr = np.array(result)
        assert mask_arr.max() == 255, "Expected some white pixels in binarized RGBA mask"

    def test_full_coverage_mask_raises_validation_error(self):
        """
        TC-INP-010
        Input:  Mask where 100% of pixels are white (full-canvas selection).
        Expected: MaskValidationError — coverage > 95% is rejected.
        """
        arr = np.full((64, 64), 255, dtype=np.uint8)
        img = Image.fromarray(arr, mode="L")
        buf = io.BytesIO()
        img.save(buf, format="PNG")
        with pytest.raises(MaskValidationError):
            MaskService.load_and_binarize_mask(buf.getvalue(), (64, 64))

    def test_empty_mask_bytes_raises_validation_error(self):
        """
        TC-INP-011
        Input:  Zero-byte mask.
        Expected: MaskValidationError with 'empty' in the message.
        """
        with pytest.raises(MaskValidationError, match="(?i)empty"):
            MaskService.load_and_binarize_mask(b"", (64, 64))


