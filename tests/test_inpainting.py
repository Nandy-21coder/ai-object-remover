# TC-INP-012 — TC-INP-015: MaskService — Preprocessing Utilities
# ===========================================================================

class TestMaskServicePreprocessing:
    """Tests for mask expansion, feathering, metrics, and compositing utilities."""

    def _get_mask(self, w=64, h=64, coverage=0.3) -> Image.Image:
        mask_bytes = _grayscale_mask_bytes(w, h, coverage)
        return MaskService.load_and_binarize_mask(mask_bytes, (w, h))

    def test_expand_mask_increases_coverage(self):
        """
        TC-INP-012
        Input:  L-mode binary mask with 30% coverage. Expand by 8 pixels.
        Expected: Selected pixel count increases after dilation.
        """
        mask = self._get_mask(64, 64, 0.3)
        metrics_before = MaskService.get_mask_metrics(mask)
        expanded = MaskService.expand_mask(mask, expansion_pixels=8)
        metrics_after = MaskService.get_mask_metrics(expanded)
        assert metrics_after["selected_pixels"] >= metrics_before["selected_pixels"], (
            "Mask expansion should not decrease selected pixel count"
        )

    def test_feather_mask_returns_pil_image(self):
        """
        TC-INP-013
        Input:  L-mode binary mask.
        Expected: feather_mask returns a PIL Image (Gaussian blur applied).
        """
        mask = self._get_mask(64, 64, 0.3)
        feathered = MaskService.feather_mask(mask, feather_radius=2.0)
        assert isinstance(feathered, Image.Image)
        assert feathered.size == mask.size

    def test_get_mask_metrics_correct_coverage(self):
        """
        TC-INP-014
        Input:  All-white 10×10 mask (100% coverage).
        Expected: coverage_percentage == 100.0.
        """
        arr = np.full((10, 10), 255, dtype=np.uint8)
        img = Image.fromarray(arr, mode="L")
        metrics = MaskService.get_mask_metrics(img)
        assert metrics["coverage_percentage"] == 100.0
        assert metrics["total_pixels"] == 100
        assert metrics["selected_pixels"] == 100

    def test_composite_inpainted_result_same_dimensions(self):
        """
        TC-INP-015
        Input:  Original 64×64 RGB image, inpainted 64×64 RGB image, L-mode mask.
        Expected: composite_inpainted_result returns a PIL Image of exactly 64×64.
        """
        original = Image.new("RGB", (64, 64), (100, 100, 100))
        inpainted = Image.new("RGB", (64, 64), (200, 200, 200))
        mask_bytes = _grayscale_mask_bytes(64, 64, 0.3)
        mask = MaskService.load_and_binarize_mask(mask_bytes, (64, 64))
        result = MaskService.composite_inpainted_result(original, inpainted, mask)
        assert result.size == (64, 64), f"Expected (64, 64), got {result.size}"


