def _png_bytes(width: int = 64, height: int = 64, color=(80, 120, 180)) -> bytes:
    """Returns raw PNG bytes for a solid-color image of the requested size."""
    img = Image.new("RGB", (width, height), color)
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    return buf.getvalue()


def _grayscale_mask_bytes(
    width: int = 64,
    height: int = 64,
    white_fraction: float = 0.3,
) -> bytes:
    """
    Returns PNG bytes for a grayscale mask where the central `white_fraction`
    of pixels are set to 255 (removal region) and the rest to 0 (preserve).
    """
    arr = np.zeros((height, width), dtype=np.uint8)
    hy = int(height * white_fraction ** 0.5 / 2)
    hx = int(width * white_fraction ** 0.5 / 2)
    cy, cx = height // 2, width // 2
    arr[max(0, cy - hy): cy + hy, max(0, cx - hx): cx + hx] = 255
    img = Image.fromarray(arr, mode="L")
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    return buf.getvalue()


def _empty_mask_bytes(width: int = 64, height: int = 64) -> bytes:
    """Returns a fully black (all-zero) PNG mask — no pixels selected."""
    img = Image.new("L", (width, height), 0)
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    return buf.getvalue()


