class TestSmartSegmentationService:
    """Unit tests for SmartSegmentationService.segment_enclosed_region."""

    def _image_bytes(self, w=100, h=100) -> bytes:
        """Returns a colorful gradient PNG for GrabCut tests."""
        arr = np.zeros((h, w, 3), dtype=np.uint8)
        for y in range(h):
            for x in range(w):
                arr[y, x] = [x * 2 % 255, y * 2 % 255, (x + y) % 255]
        img = Image.fromarray(arr, mode="RGB")
        buf = io.BytesIO()
        img.save(buf, format="PNG")
        return buf.getvalue()

    def test_valid_polygon_returns_png_bytes(self):
        """
        TC-INP-025
        Input:  100×100 gradient image, 5 points forming a polygon around the center.
        Expected: Returns non-empty PNG bytes decodable by Pillow.
        """
        image_bytes = self._image_bytes(100, 100)
        points = [
            {"x": 30, "y": 20},
            {"x": 70, "y": 20},
            {"x": 80, "y": 70},
            {"x": 50, "y": 85},
            {"x": 20, "y": 70},
        ]
        result = SmartSegmentationService.segment_enclosed_region(
            image_bytes, points, mode="smart_object"
        )
        assert isinstance(result, bytes) and len(result) > 0
        # Must be valid PNG
        img = Image.open(io.BytesIO(result))
        assert img.format == "PNG"

    def test_fewer_than_3_points_raises_value_error(self):
        """
        TC-INP-026
        Input:  Only 2 polygon points (below minimum of 3).
        Expected: ValueError is raised with a message about insufficient points.
        """
        image_bytes = self._image_bytes(100, 100)
        with pytest.raises(ValueError, match="(?i)at least 3"):
            SmartSegmentationService.segment_enclosed_region(
                image_bytes, [{"x": 10, "y": 10}, {"x": 50, "y": 50}]
            )

    def test_fill_interior_mode_returns_png(self):
        """
        TC-INP-027
        Input:  100×100 image, 4 polygon points, mode='fill_interior'.
        Expected: Returns PNG bytes (fill_interior bypasses GrabCut and directly
                  fills the polygon interior).
        """
        image_bytes = self._image_bytes(100, 100)
        points = [
            {"x": 25, "y": 25},
            {"x": 75, "y": 25},
            {"x": 75, "y": 75},
            {"x": 25, "y": 75},
        ]
        result = SmartSegmentationService.segment_enclosed_region(
            image_bytes, points, mode="fill_interior"
        )
        assert isinstance(result, bytes) and len(result) > 0
        img = Image.open(io.BytesIO(result))
        assert img.format == "PNG"
